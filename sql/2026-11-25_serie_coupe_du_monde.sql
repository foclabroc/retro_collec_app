-- 2) tirage rare dans les paquets normaux (la serie wc est exclue du tirage des sagas)
create or replace function public.rc__saga_roll()
 returns text
 language sql
as $function$
  select case
    when random() < public.rc__cfg('pk', 0.15) / 100 then (select id from public.rc_cards where saga = 'pk' order by random() limit 1)
    when random() < public.rc__cfg('da', 0.15) / 100 then (select id from public.rc_cards where saga = 'da' order by random() limit 1)
    when random() < public.rc__cfg('db', 0.15) / 100 then (select id from public.rc_cards where saga = 'db' order by random() limit 1)
    when random() < public.rc__cfg('wc', 0.15) / 100 then (select id from public.rc_cards where saga = 'wc' order by random() limit 1)
    when random() < public.rc__cfg('saga', 3.2) / 100 then (select id from public.rc_cards where saga is not null and saga not in ('pk', 'da', 'db', 'wc') order by random() limit 1)
  end $function$;
alter function public.rc__saga_roll() owner to rc_owner;

-- 3) prix du booster : 400 pieces
create or replace function public.rc__pack_price(k text)
 returns integer
 language sql
 stable
as $function$
  select (case k when 'free' then 0 when 'mixte' then public.rc__cfg('mixte', 100)::int when 'console' then public.rc__cfg('console', 150)::int
                 when 'premium' then public.rc__cfg('premium', 400)::int
                 when 'mystery' then public.rc__cfg('mystery', 120)::int when 'dragonball' then 400 when 'football' then 400
                 when 'gift' then 0 when 'lot' then 0 end)
         * (100 - public.rc__promo(k)) / 100 $function$;
alter function public.rc__pack_price(text) owner to rc_owner;

-- 4) le booster : 8 cartes wc differentes
create or replace function public.rc__draw_wc()
 returns jsonb
 language plpgsql
 security definer
 set search_path to 'public', 'extensions'
as $function$
declare
  i int; r int; c text; rr int; got text[] := '{}'; res jsonb := '[]'::jsonb;
begin
  for i in 1..8 loop
    r := case when i <= 5 then 2 when i = 6 then 3 when i = 7 then case when random() < 0.3 then 4 else 3 end else 4 end;
    select id, rarity into c, rr from public.rc_cards
     where saga = 'wc' and rarity = r and not (id = any(got)) order by random() limit 1;
    if c is null then
      select id, rarity into c, rr from public.rc_cards where saga = 'wc' and not (id = any(got)) order by random() limit 1;
    end if;
    if c is null then raise exception 'catalogue vide'; end if;
    got := got || c;
    res := res || jsonb_build_object('c', c, 'f', case when rr >= 4 then 1 else 0 end, 'r', rr);
    c := null;
  end loop;
  return res;
end $function$;
alter function public.rc__draw_wc() owner to rc_owner;

