select (jsonb_populate_record(null::public.rc_cards,
          to_jsonb(b) || jsonb_build_object(
            'id', 'sg_' || x.saga || '_' || lpad(x.n::text, 2, '0'),
            'sys', 'sg_' || x.saga, 'num', x.n, 'n', x.n,
            'rarity', 3, 'saga', x.saga, 'base', b.id))).*
